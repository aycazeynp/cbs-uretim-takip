-- Supabase SQL Editor'da tamamını bir kez çalıştırın.
-- Önce Authentication > Providers > Email içinde 'Confirm email' ayarını ihtiyacınıza göre belirleyin.
-- Güvenlik: Auth > Settings'den herkese açık yeni kayıt (sign ups) seçeneğini KAPATIN.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 email text not null,
 role text not null default 'viewer' check (role in ('admin','editor','viewer')),
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 code text not null unique check (length(trim(code)) between 1 and 40),
 created_at timestamptz not null default now()
);
create table if not exists public.batches (
 id bigint generated by default as identity primary key,
 order_id bigint not null references public.orders(id) on delete restrict,
 litre integer not null check (litre in (5,9,26,45,83,149,180)),
 target integer not null default 0 check (target>=0),
 start_date date, end_date date,
 unique(order_id,litre),
 constraint dates_order check (end_date is null or start_date is null or end_date >= start_date)
);
create table if not exists public.serials (
 id bigint generated by default as identity primary key,
 batch_id bigint not null references public.batches(id) on delete restrict,
 serial text not null unique check (length(trim(serial)) between 1 and 80),
 stage text not null default 'SAC KESME' check(stage in ('SAC KESME','PRES','KORDON','BÜKÜM','DOĞRULTMA','ÇEVRE KAYNAK','MONTAJ','BOYA','PAKETLEME','TAMAMLANDI')),
 updated_at timestamptz not null default now()
);
create table if not exists public.audit (
 id bigint generated by default as identity primary key,
 actor uuid references auth.users(id), email text, action text not null, details text,
 at timestamptz not null default now()
);
create index if not exists serials_batch_idx on public.serials(batch_id);
create index if not exists batches_order_idx on public.batches(order_id);
create index if not exists audit_at_idx on public.audit(at desc);

-- SECURITY DEFINER yardımcı fonksiyon: profiles tablosundaki RLS döngüsünü önler.
create or replace function public.cbs_role() returns text
language sql stable security definer set search_path = '' as $$
 select role from public.profiles where id = (select auth.uid()) and active = true limit 1
$$;
revoke all on function public.cbs_role() from public;
grant execute on function public.cbs_role() to authenticated;

-- Yeni Auth kullanıcısı eklendiğinde profil otomatik açılır; yetkisi varsayılan viewer.
create or replace function public.cbs_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
 insert into public.profiles(id,email,role,active)
 values(new.id, coalesce(new.email,''), 'viewer', true)
 on conflict(id) do update set email=excluded.email;
 return new;
end $$;
drop trigger if exists cbs_auth_user_created on auth.users;
create trigger cbs_auth_user_created after insert on auth.users
for each row execute function public.cbs_new_user();

-- İşlem günlüğü DB tarafında tutulur, kullanıcı tarafından sahte kayıt oluşturulamaz.
create or replace function public.cbs_audit_change() returns trigger
language plpgsql security definer set search_path = '' as $$
declare actor_email text;
begin
 select email into actor_email from public.profiles where id=auth.uid();
 insert into public.audit(actor,email,action,details)
 values(auth.uid(),actor_email,TG_OP||' '||TG_TABLE_NAME,
  case when TG_OP='DELETE' then to_jsonb(old)::text else to_jsonb(new)::text end);
 return coalesce(new,old);
end $$;
do $$ declare tbl text; begin
 foreach tbl in array array['orders','batches','serials','profiles'] loop
  execute format('drop trigger if exists cbs_audit_%I on public.%I',tbl,tbl);
  execute format('create trigger cbs_audit_%I after insert or update or delete on public.%I for each row execute function public.cbs_audit_change()',tbl,tbl);
 end loop;
end $$;

alter table public.profiles enable row level security;
alter table public.orders enable row level security;
alter table public.batches enable row level security;
alter table public.serials enable row level security;
alter table public.audit enable row level security;

-- Profil: kendini oku; admin herkesi görür ve yetkileri düzenler.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated
using (id=(select auth.uid()) or (select public.cbs_role())='admin');
drop policy if exists profiles_admin_update on public.profiles;
create policy profiles_admin_update on public.profiles for update to authenticated
using ((select public.cbs_role())='admin') with check ((select public.cbs_role())='admin');

-- Veri okuma: yalnızca aktif hesabı olan üç rol.
do $$ declare tbl text; begin
 foreach tbl in array array['orders','batches','serials'] loop
  execute format('drop policy if exists %I on public.%I',tbl||'_read',tbl);
  execute format('create policy %I on public.%I for select to authenticated using ((select public.cbs_role()) in (''admin'',''editor'',''viewer''))',tbl||'_read',tbl);
  execute format('drop policy if exists %I on public.%I',tbl||'_insert',tbl);
  execute format('create policy %I on public.%I for insert to authenticated with check ((select public.cbs_role()) in (''admin'',''editor''))',tbl||'_insert',tbl);
  execute format('drop policy if exists %I on public.%I',tbl||'_update',tbl);
  execute format('create policy %I on public.%I for update to authenticated using ((select public.cbs_role()) in (''admin'',''editor'')) with check ((select public.cbs_role()) in (''admin'',''editor''))',tbl||'_update',tbl);
 end loop;
end $$;
drop policy if exists audit_admin_read on public.audit;
create policy audit_admin_read on public.audit for select to authenticated
using ((select public.cbs_role())='admin');

